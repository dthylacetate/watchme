import { cpSync, existsSync, mkdirSync, readFileSync, renameSync, rmSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";

const PRESERVED_ENTRIES = [".env", "data", "logs", "backups"];

function writeReleaseFiles(root, targetDir) {
  mkdirSync(targetDir, { recursive: true });
  mkdirSync(resolve(targetDir, "dist"), { recursive: true });

  cpSync(resolve(root, "refactor/apps/server/dist"), resolve(targetDir, "dist"), { recursive: true });
  cpSync(resolve(root, "refactor/apps/web/out"), resolve(targetDir, "public"), { recursive: true });

  const releaseEnvExample = [
    "PORT=3000",
    "DB_PATH=./data/watchme.db",
    "STATIC_DIR=./public",
    "HASH_SECRET=replace-me",
    "OFFLINE_AFTER_SECONDS=90",
    "RETENTION_DAYS=30",
    "CLEANUP_INTERVAL_MINUTES=60",
    "DISPLAY_NAME=WatchMe",
    "SITE_TITLE=WatchMe Now",
    "SITE_DESC=What is WatchMe doing right now?",
    "SITE_FAVICON=/favicon.ico",
    "DEVICE_TOKEN_1=dev-token:dev-desktop:Dev Desktop:windows"
  ].join("\n");

  writeFileSync(resolve(targetDir, ".env.example"), `${releaseEnvExample}\n`, "utf8");

  const packageJson = {
    name: "watchme-server-release",
    private: true,
    type: "module",
    scripts: {
      start: "node dist/index.js"
    },
    dependencies: {
      "@hono/node-server": "^1.14.4",
      "hono": "^4.12.23",
      "zod": "^3.25.76"
    }
  };

  writeFileSync(
    resolve(targetDir, "package.json"),
    `${JSON.stringify(packageJson, null, 2)}\n`,
    "utf8"
  );

  const readme = `
# WatchMe server release

This folder is generated by \`npm run package:server\`.

## Run

\`\`\`bash
npm install
cp .env.example .env
npm run start
\`\`\`
`.trimStart();

  writeFileSync(resolve(targetDir, "README.md"), readme, "utf8");

  if (existsSync(resolve(root, "refactor/docs/deployment.md"))) {
    cpSync(resolve(root, "refactor/docs/deployment.md"), resolve(targetDir, "deployment.md"));
  }
}

function preserveExistingEntries(targetDir, preserveDir) {
  if (!existsSync(targetDir)) {
    return;
  }

  mkdirSync(preserveDir, { recursive: true });
  for (const entry of PRESERVED_ENTRIES) {
    const source = resolve(targetDir, entry);
    if (!existsSync(source)) {
      continue;
    }

    cpSync(source, resolve(preserveDir, entry), { recursive: true });
  }
}

function restorePreservedEntries(tempDir, preserveDir) {
  if (!existsSync(preserveDir)) {
    return;
  }

  for (const entry of PRESERVED_ENTRIES) {
    const source = resolve(preserveDir, entry);
    if (!existsSync(source)) {
      continue;
    }

    cpSync(source, resolve(tempDir, entry), { recursive: true });
  }
}

export function prepareServerRelease(rootArg = ".", targetArg = "refactor/.release/server") {
  const root = resolve(rootArg);
  const targetDir = resolve(targetArg);
  const tempDir = resolve(dirname(targetDir), `${targetDir.split(/[\\/]/).at(-1)}.tmp`);
  const preserveDir = resolve(dirname(targetDir), `${targetDir.split(/[\\/]/).at(-1)}.preserve`);

  rmSync(tempDir, { recursive: true, force: true });
  rmSync(preserveDir, { recursive: true, force: true });

  preserveExistingEntries(targetDir, preserveDir);
  writeReleaseFiles(root, tempDir);
  restorePreservedEntries(tempDir, preserveDir);

  rmSync(targetDir, { recursive: true, force: true });
  renameSync(tempDir, targetDir);
  rmSync(preserveDir, { recursive: true, force: true });

  return targetDir;
}

export function readReleaseReadme(targetDir) {
  return readFileSync(resolve(targetDir, "README.md"), "utf8");
}
